function seedId(tag: string): string {
  const slug = tag
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
  return `seed-${slug}`;
}

export function seedBank(): BankTag[] {
  return SEED_WORDS.map((item) => ({
    id: seedId(item.tag),
    tag: item.tag,
    note: item.note,
    enabled: true,
  }));
}

export function wordCategory(note: string): string {
  const head = note.split("。")[0]?.trim() ?? "";
  return (SEED_CATEGORIES as readonly string[]).includes(head) ? head : head || "その他";
}

export function mergeSeedWords(existing: BankTag[]): BankTag[] {
  const have = new Set(existing.map((item) => item.tag.trim().toLowerCase()));
  const missing = seedBank().filter((item) => !have.has(item.tag.toLowerCase()));
  return [...existing, ...missing];
}
